const checkedDate = '2026-08-01'
const scopeDomainIds = new Set(['iot-embedded', 'automotive', 'ai', 'security-rnd'])

function posting({
  id,
  roleId,
  companyName,
  originalJobTitle,
  postingUrl,
  sourceType,
  status = 'open',
  applicationAvailable = status === 'open',
  market = 'international',
  country,
  location,
  workMode = 'unknown',
  employmentType = '정규직',
  careerLevel = 'unknown',
  requiredYearsMin = null,
  requiredYearsMax = null,
  level,
  score,
  titleMatch = false,
  reasons,
  matchedResponsibilities,
  unmatchedCoreResponsibilities = [],
  extracted,
  sourceHeadings = ['Responsibilities', 'Qualifications'],
  verificationNotes = [],
  extractionNotes = [],
  limitations = [],
}) {
  const target = roleResearchTargetById[roleId]
  if (!target) throw new Error(`Unknown research role: ${roleId}`)
  return prepareEnrichedPosting({
    id,
    roleId,
    domainId: target.domainId,
    familyId: target.familyId,
    companyName,
    originalJobTitle,
    normalizedRoleTitle: target.roleTitle,
    market,
    country,
    location,
    workMode,
    employmentType,
    careerLevel,
    requiredYearsMin,
    requiredYearsMax,
    source: {
      postingUrl,
      sourceType,
      checkedDate,
      status,
      titleVerified: true,
      companyVerified: true,
      bodyVerified: true,
      applicationAvailable,
      verificationNotes: [
        '2026-08-01에 개별 공고 URL을 GET 요청 또는 공식 ATS API로 열어 제목·회사·본문을 확인했다.',
        ...verificationNotes,
      ],
    },
    match: {
      level,
      score,
      titleMatch,
      responsibilityMatchCount: matchedResponsibilities.length,
      foundationMatchCount: Math.min(3, extracted.requirements?.length || 0),
      reasons,
      matchedResponsibilities,
      unmatchedCoreResponsibilities,
    },
    extracted,
    evidence: { sourceHeadings, extractionNotes, limitations },
  })
}

function mappedSource(source, mappings) {
  return mappings.map((mapping) => posting({
    ...source,
    ...mapping,
    reasons: mapping.reasons || [
      mapping.level === 'exact'
        ? `공고 직무명이 “${roleResearchTargetById[mapping.roleId].roleTitle}”과 직접 대응한다.`
        : `공고 직무명은 다르지만 “${roleResearchTargetById[mapping.roleId].roleTitle}”의 핵심 책임이 주요 업무로 확인된다.`,
      `역할별로 독립된 업무 근거 ${mapping.matchedResponsibilities.length}개를 공고 본문에서 확인했다.`,
    ],
    extracted: { ...source.extracted, ...(mapping.extracted || {}) },
  }))
}

