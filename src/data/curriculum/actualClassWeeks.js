function guidedLab({ week, id, title, objective, concepts, steps, artifacts, evidenceOptions, correctEvidenceIds, conclusion }) {
  return {
    id,
    week,
    title,
    kind: 'guided-observation',
    activityType: 'investigation',
    path: 'required',
    estimatedMinutes: 35,
    objective,
    prerequisites: concepts,
    requiredTools: ['브라우저', 'SecTrack의 고정 합성 자료'],
    safeScope: '브라우저에 포함된 교육용 고정 전사만 읽습니다. 실제 시스템, 계정, 증거 파일 또는 외부 호스트에는 연결하지 않습니다.',
    hints: ['도구 이름보다 그 도구로 확인한 사실을 먼저 찾으세요.', '한 증거만으로 실행·침입·유출 전체를 확정하지 마세요.', '시간·호스트·프로세스·통신 주체가 맞는지 교차 확인하세요.'],
    successCriteria: ['직접 관찰 가능한 증거만 선택', '서로 다른 증거의 연결 근거 설명', '확인하지 못한 범위를 결론에서 분리'],
    submissionSchema: recordSchema,
    rubric,
    relatedConceptIds: concepts,
    scenario: {
      title,
      steps,
      artifacts,
      evidenceOptions,
      correctEvidenceIds,
      conclusion,
      reflection: {
        prompt: '선택한 증거 중 두 가지 이상을 시간·호스트·프로세스 또는 통신 정보로 연결해 40자 이상 설명하세요.',
        minimumLength: 40,
      },
    },
  }
}

function quiz(week, entries) {
  return entries.map(([conceptId, question, options, answer, explanation], index) => ({
    id: `w${week}actualq${index + 1}`,
    conceptIds: [conceptId],
    difficulty: index < 2 ? 'foundation' : index < 4 ? 'application' : 'analysis',
    remediationModuleIds: [conceptId],
    question,
    options,
    answer,
    explanation,
  }))
}

